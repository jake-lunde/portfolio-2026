#!/usr/bin/env node
/* One-off: bake the Greenlight performance graph's price data.
 *
 *   node scripts/bake-graph-data.mjs <normalized.json>
 *
 * Reads the normalized quote dump ({asOf, note, symbols: {SYM: {daily:
 * [[YYYY-MM-DD, close]…], intraday: [[minuteOfDay, price]…], prevClose}}})
 * and writes src/components/case/graphData.ts, thinned per range so the
 * file stays small:
 *   - daily closes for the last year (1W/1M/3M/1Y slice this)
 *   - weekly closes (every 5th trading day, counted back from the as-of
 *     date, plus the first day) for the full 5Y
 *   - the 5-minute regular-hours intraday points for the as-of day (1D)
 * Every symbol shares one date axis (checked). Numbers to 2 decimals. */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const src = process.argv[2]
if (!src) {
  console.error('usage: node scripts/bake-graph-data.mjs <normalized.json>')
  process.exit(1)
}

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'src/components/case/graphData.ts')
const SYMBOLS = ['NVDA', 'AAPL', 'NKE', 'DIS', 'SPY']

const data = JSON.parse(fs.readFileSync(src, 'utf8'))
const asOf = data.asOf
const r2 = (n) => Math.round(n * 100) / 100

const ref = data.symbols.SPY
const dates = ref.daily.map((d) => d[0])
const minutes = ref.intraday.map((d) => d[0])
for (const s of SYMBOLS) {
  const v = data.symbols[s]
  if (!v) throw new Error(`missing ${s}`)
  if (v.daily.map((d) => d[0]).join() !== dates.join()) throw new Error(`${s}: daily dates differ from SPY`)
  if (v.intraday.map((d) => d[0]).join() !== minutes.join()) throw new Error(`${s}: intraday minutes differ from SPY`)
}
if (dates.at(-1) !== asOf) throw new Error(`last daily date ${dates.at(-1)} is not asOf ${asOf}`)

/* one year back from the as-of date, inclusive */
const [y, m, d] = asOf.split('-').map(Number)
const yearAgo = `${y - 1}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`
const dailyFrom = dates.findIndex((t) => t >= yearAgo)

const weeklyIdx = []
for (let i = dates.length - 1; i >= 0; i -= 5) weeklyIdx.unshift(i)
if (weeklyIdx[0] !== 0) weeklyIdx.unshift(0)

const list = (a) => a.join(',')
const strs = (a) => a.map((s) => `'${s}'`).join(',')

let out = `/* Greenlight performance graph data (GraphPlate.tsx).
   GENERATED by scripts/bake-graph-data.mjs from a one-off quote dump; to
   refresh, re-run the script on a new dump rather than editing by hand.
   Source: ${data.note}
   As of ${asOf}. SPY stands in for the S&P 500.
   Ranges: 1W/1M/3M/1Y slice DAILY (one year of closes), 5Y uses WEEKLY
   (every 5th trading day back from the as-of date, plus the first day),
   1D uses INTRADAY (5-minute regular-hours prices, minute of day). */

export const AS_OF = '${asOf}'

export type Ticker = ${SYMBOLS.map((s) => `'${s}'`).join(' | ')}

export const DAILY_DATES: readonly string[] = [${strs(dates.slice(dailyFrom))}]

export const WEEKLY_DATES: readonly string[] = [${strs(weeklyIdx.map((i) => dates[i]))}]

/* minutes after midnight, US Eastern: 570 = 9:30 AM */
export const INTRADAY_MINUTES: readonly number[] = [${list(minutes)}]

export type PriceSeries = {
  daily: readonly number[]
  weekly: readonly number[]
  intraday: readonly number[]
}

export const PRICES: Record<Ticker, PriceSeries> = {
`
for (const s of SYMBOLS) {
  const v = data.symbols[s]
  const closes = v.daily.map((p) => r2(p[1]))
  out += `  ${s}: {
    daily: [${list(closes.slice(dailyFrom))}],
    weekly: [${list(weeklyIdx.map((i) => closes[i]))}],
    intraday: [${list(v.intraday.map((p) => r2(p[1])))}],
  },
`
}
out += `}
`
fs.writeFileSync(OUT, out)
console.log(`wrote ${path.relative(ROOT, OUT)}: ${(Buffer.byteLength(out) / 1024).toFixed(1)} KB, daily ${dates.length - dailyFrom}, weekly ${weeklyIdx.length}, intraday ${minutes.length}`)
