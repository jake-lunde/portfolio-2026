#!/usr/bin/env node
/* PreToolUse[Edit|Write] — CLAUDE.md §2: token-pipeline output is never
   hand-edited. Exit 2 = block; stderr goes back to the agent. */
const raw = await new Promise((resolve) => {
  let d = ''
  process.stdin.on('data', (c) => (d += c))
  process.stdin.on('end', () => resolve(d))
})

let input
try {
  input = JSON.parse(raw)
} catch {
  process.exit(0) // malformed payload — never brick the tool
}

const p = input?.tool_input?.file_path ?? ''
const GENERATED =
  /(?:^|\/)(?:tokens\.generated\.css|tokens\.generated\.ts|motion\.generated\.ts)$|\/src\/styles\/generated\//

if (GENERATED.test(p)) {
  console.error(
    `${p} is generated by the token pipeline (CLAUDE.md §2 — never hand-edit). ` +
      'Edit the source JSON in tokens/ and run `npm run tokens:build` instead.'
  )
  process.exit(2)
}
