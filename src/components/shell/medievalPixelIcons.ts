/* Medieval pixel icon art — the medieval skin's own 32px bitmap tier, so it
   stops borrowing the classic pixel art (the seven names that never had a
   woodcut line-art variant) or drawing 1.5px strokes among bitmaps (the
   rest). Same grid contract as pixelIcons.ts — '#' ink, 'o' interior
   (compiles to nothing), '.' outside, 32×32 — so the compile path and the
   hover-strip mechanics are shared; only the drawings are this skin's.

   THE FORM is the woodblock, not the bitmap: a print pulled from a cut
   block, the way a 1392 book would carry a picture. Every icon is a plate —
   a double rule frames it (outer at 0/31, inner at 2/29, picture inside
   3..28), the way a woodcut sits in its border on the page. Inside, ink is
   heavier than the classic tier: 2px contours, solid blacks for the deep
   shade, and TONE IS HATCH — parallel diagonal lines every third cell for
   glass, wax, a bell, a shield's field, cross-hatched nowhere (too dark at
   32px). Nothing is dithered; a woodcut has no half-tone, only strokes.

   Metaphors follow the medieval line art in Icon.tsx (the sun in
   splendour, the keep, the oubliette, the neume …); the seven names that
   had no medieval variant get one here for the first time (bell,
   horseshoe, heraldic rose, hourglass, swallow, peaks, estoile).

   Grids were generated, not hand-counted (rings, polygons, hatch, mirrored
   quadrants) and reviewed as block art in the terminal before they were
   emitted here; the ASCII in this file is the source of truth. Hover
   cycles (MEDIEVAL_FRAMES) derive from the base grids with the ops from
   pixelIcons.ts — every op stays inside the plate, so the frame never
   moves. */

