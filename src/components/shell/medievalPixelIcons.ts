/* Hover cycles. Regions and coordinates are the base grids' above; the
   PLATE bound keeps every shift inside the double rule. Cycles ping-pong
   ([a, b, c, b]) or end where a fresh one starts, as in the classic tier. */
type Region = [x0: number, y0: number, x1: number, y1: number]
const PLATE: Region = [3, 3, 28, 28]
const bounce = (g: Grid) => [g, shift(g, 0, -1, PLATE, PLATE), shift(g, 0, -2, PLATE, PLATE), shift(g, 0, -1, PLATE, PLATE)]
const sway = (g: Grid, r: Region) => [g, shift(g, -1, 0, r, PLATE), g, shift(g, 1, 0, r, PLATE)]

